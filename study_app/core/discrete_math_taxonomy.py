def discrete_template_ids() -> set[str]:
    return set(DISCRETE_TEMPLATE_INFO)


def template_for_module(module: str) -> tuple[str, str]:
    template_id = MODULE_TO_TEMPLATE[module]
    return template_id, DISCRETE_TEMPLATE_INFO[template_id][1]


def classify_discrete_text(text: str, *, fallback_module: str = "", fallback_topic: str = "") -> tuple[str, str, str]:
    normalized = re.sub(r"\s+", "", str(text or ""))
    known_topics = sorted(
        (topic for topics in MODULE_TOPICS.values() for topic in topics),
        key=lambda topic: len(re.sub(r"\s+", "", topic)),
        reverse=True,
    )
    exact_topic = next(
        (topic for topic in known_topics if re.sub(r"\s+", "", topic) in normalized),
        "",
    )
    exact_module = next((name for name, topics in MODULE_TOPICS.items() if exact_topic in topics), "")
    best_score = 0
    best_topic = ""
    for candidate, keywords in TOPIC_KEYWORDS.items():
        candidate_module = next((name for name, topics in MODULE_TOPICS.items() if candidate in topics), "")
        if exact_module and candidate_module != exact_module:
            continue
        score = sum(1 for keyword in keywords if re.sub(r"\s+", "", keyword).lower() in normalized.lower())
        if score > best_score or (score == best_score and score > 0 and len(candidate) > len(best_topic)):
            best_score = score
            best_topic = candidate
    # Keyword evidence is allowed to refine a broader literal topic mention;
    # e.g. "卡诺图" should route a sentence containing "布尔函数" to the
    # minimisation topic rather than the generic Boolean-function topic.
    topic = best_topic or exact_topic or fallback_topic
    module = next((name for name, topics in MODULE_TOPICS.items() if topic in topics), "") or fallback_module
    if not module:
        module = "命题逻辑"
    if not topic:
        topic = MODULE_TOPICS[module][0]
    template_id = MODULE_TO_TEMPLATE[module]
    return template_id, module, topic

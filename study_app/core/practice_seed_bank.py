def seeds_for_template(template_id: str, limit: int = 4) -> list[PracticeSeed]:
    return [seed for seed in PRACTICE_SEEDS if seed.template_id == template_id][:limit]


def seeds_for_homework(template_id: str, topic: str, limit: int = 3) -> list[PracticeSeed]:
    direct = seeds_for_template(template_id, limit)
    if direct:
        return direct
    topic_keys = [part for part in topic.replace("、", " ").replace("/", " ").split() if len(part) >= 2]
    scored: list[PracticeSeed] = []
    for seed in PRACTICE_SEEDS:
        haystack = " ".join((seed.title, seed.seed_statement, " ".join(seed.tested_points)))
        if any(key in haystack for key in topic_keys):
            scored.append(seed)
    return scored[:limit]
